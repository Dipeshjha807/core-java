class multi_array {
    public static void main(String[] args) {
        int num[][] = new int[3][4];

         num[0][2]=4;//giving random values by own
         num[2][1]=5;
         num[0][0]=23;
         for(int i=0; i<3;i++){
            for(int j=0;j<4;j++)
            {
                System.out.println(num[i][j]);
              
            }
         }
        
        }
    }
